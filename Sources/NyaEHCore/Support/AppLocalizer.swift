    func versionCensorshipDescription(_ value: String) -> String {
        let normalized = value.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        switch normalized {
        case "", "unknown": return string(.unknown)
        case "uncensored": return string(.uncensored)
        case "mosaic censorship":
            switch language {
            case .zhHans: return "马赛克"
            case .zhHant: return "馬賽克"
            case .ja: return "モザイク"
            case .ko: return "모자이크"
            case .en, .system: return "Mosaic"
            }
        case "full censored":
            switch language {
            case .zhHans, .zhHant, .ja: return "全修正"
            case .ko: return "전체 수정"
            case .en, .system: return "Full Censored"
            }
        default:
            return normalized.split(separator: " ").map { $0.capitalized }.joined(separator: " ")
        }
    }

